#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

function parseArgs(argv) {
  const options = { check: false, workspaceRoot: process.cwd(), output: null };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') options.check = true;
    else if (arg === '--workspace-root') options.workspaceRoot = path.resolve(argv[++i] ?? '');
    else if (arg === '--output') options.output = path.resolve(argv[++i] ?? '');
    else throw new Error(`Unknown argument: ${arg}`);
  }
  options.output ??= path.join(options.workspaceRoot, 'packages/installer/src/catalog.generated.mjs');
  return options;
}

export async function generateCatalog(workspaceRoot) {
  const rootManifest = JSON.parse(await fs.readFile(path.join(workspaceRoot, 'package.json'), 'utf8'));
  const workspaces = Array.isArray(rootManifest.workspaces) ? rootManifest.workspaces : [];
  const records = [];
  for (const pattern of workspaces) {
    const packagePaths = pattern.includes('*')
      ? (await fs.readdir(path.join(workspaceRoot, pattern.slice(0, pattern.indexOf('*'))), { withFileTypes: true }))
        .filter((entry) => entry.isDirectory())
        .map((entry) => path.join(pattern.slice(0, pattern.indexOf('*')), entry.name))
      : [pattern];
    for (const packagePathRelative of packagePaths) {
      const packagePath = path.join(workspaceRoot, packagePathRelative, 'package.json');
      let manifest;
      try { manifest = JSON.parse(await fs.readFile(packagePath, 'utf8')); } catch { continue; }
      if (!manifest.omp?.extensions) continue;
      records.push({
        id: path.basename(path.dirname(packagePath)),
        packageName: manifest.name,
        description: manifest.description,
      });
    }
  }
  return records;
}

export function renderCatalog(records) {
  return `// Generated by scripts/sync-installer-catalog.mjs. Do not edit.\nexport const catalog = Object.freeze(${JSON.stringify(records, null, 2)});\n`;
}

export async function syncCatalog({ workspaceRoot, output, check = false }) {
  const expected = renderCatalog(await generateCatalog(workspaceRoot));
  let actual = null;
  try { actual = await fs.readFile(output, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (check) {
    if (actual !== expected) throw new Error(`Installer catalog is stale: ${output}`);
    return false;
  }
  await fs.mkdir(path.dirname(output), { recursive: true });
  if (actual !== expected) await fs.writeFile(output, expected);
  return actual !== expected;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try { await syncCatalog(parseArgs(process.argv.slice(2))); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
